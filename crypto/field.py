"""
Finite Field GF(q) and Elliptic Curve arithmetic for Feldman Verifiable Secret Sharing (VSS).

Parameter selection:
We use NIST P-256 (secp256r1) curve parameters:
- Field Prime p: 2^256 - 2^224 + 2^192 + 2^96 - 1
- Group Order q (scalar field modulus): prime order n of the generator point G.
- Generator G = (Gx, Gy).

This guarantees mathematical compatibility between Shamir Secret Sharing over GF(q)
and Feldman commitments in the group generated by G, directly resolving the critical
architectural requirement that sharing field modulus == group order.
"""

from dataclasses import dataclass
from typing import Optional, Tuple
import secrets

# NIST P-256 Prime Field Modulus
P = 0xFFFFFFFF00000001000000000000000000000000FFFFFFFFFFFFFFFFFFFFFFFF
A = -3
B = 0x5AC635D8AA3A93E7B3EBBD55769886BC651D06B0CC53B0F63BCE3C3E27D2604B

# Scalar Field Modulus (Group Order q)
Q = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551

# Standard Generator Point G = (Gx, Gy)
GX = 0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296
GY = 0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5


@dataclass(frozen=True)
class ECPoint:
    x: Optional[int]
    y: Optional[int]
    is_infinity: bool = False

    def __repr__(self) -> str:
        if self.is_infinity:
            return "Point(Infinity)"
        return f"Point({hex(self.x)[:10]}..., {hex(self.y)[:10]}...)"

    def to_hex(self) -> str:
        if self.is_infinity:
            return "00"
        return f"04{self.x:064x}{self.y:064x}"

    @classmethod
    def from_hex(cls, h: str) -> "ECPoint":
        if h == "00":
            return cls(None, None, is_infinity=True)
        if h.startswith("04") and len(h) == 130:
            x = int(h[2:66], 16)
            y = int(h[66:130], 16)
            return cls(x, y, is_infinity=False)
        raise ValueError("Invalid ECPoint hex representation")


INFINITY = ECPoint(None, None, is_infinity=True)
G = ECPoint(GX, GY, is_infinity=False)


def mod_inverse(a: int, m: int = Q) -> int:
    """Constant-time/Fermat inverse for prime modulus m."""
    a = a % m
    if a == 0:
        raise ZeroDivisionError("Division by zero in finite field")
    return pow(a, m - 2, m)


def point_add(p1: ECPoint, p2: ECPoint) -> ECPoint:
    """Elliptic curve point addition over GF(P)."""
    if p1.is_infinity:
        return p2
    if p2.is_infinity:
        return p1

    if p1.x == p2.x:
        if (p1.y + p2.y) % P == 0:
            return INFINITY
        # Point doubling
        lam = (3 * p1.x * p1.x + A) * pow(2 * p1.y, P - 2, P) % P
    else:
        lam = (p2.y - p1.y) * pow(p2.x - p1.x, P - 2, P) % P

    x3 = (lam * lam - p1.x - p2.x) % P
    y3 = (lam * (p1.x - x3) - p1.y) % P
    return ECPoint(x3, y3, is_infinity=False)


def point_mul(k: int, p: ECPoint = G) -> ECPoint:
    """Scalar multiplication k * P using double-and-add."""
    k = k % Q
    if k == 0 or p.is_infinity:
        return INFINITY

    result = INFINITY
    addend = p

    while k > 0:
        if k & 1:
            result = point_add(result, addend)
        addend = point_add(addend, addend)
        k >>= 1

    return result


def generate_random_scalar() -> int:
    """Generates a cryptographically secure random non-zero scalar in GF(q)."""
    while True:
        s = secrets.randbelow(Q)
        if s > 0:
            return s
